#!/usr/bin/env bash
# Runs rollback-test.sh for each step of the split and for PR #482, then writes the
# results table to docs/rollback-results.md.
# Usage: rollback-matrix.sh
source "$(dirname "$0")/lib.sh"

DIR="$(cd "$(dirname "$0")" && pwd)"
OUT="$ROOT/docs/rollback-results.md"
CASES="main:split/1-expand split/1-expand:split/2-migrate split/2-migrate:split/3-contract split/3-contract:split/4-drop main:pr-482-minor-units"
expect() { case "$1" in *pr-482*) echo FAIL ;; *) echo PASS ;; esac; }

rm -f "$STATE/rollback-results.tsv"
for c in $CASES; do
  "$DIR/rollback-test.sh" "${c%%:*}" "${c#*:}" || true
done

{
  echo "# Rollback test results"
  echo
  echo "Generated by \`demo/scripts/rollback-matrix.sh\` on $(date -u +'%Y-%m-%d %H:%M UTC')."
  echo "Each row: clean start at *from*, deploy ledger-service then settlement-service at *to*, roll ledger-service"
  echo "back, then settlement-service, with ${TRAFFIC:-20} settlements after every step. PASS means every stage had both services"
  echo "healthy, every settlement booked once, no £0.00 rows, an empty dead-letter topic and a correct reconciliation total."
  echo
  echo "| From | To | Expected | Result | First problem |"
  echo "|---|---|---|---|---|"
  while IFS="$(printf '\t')" read -r from to result why; do
    echo "| \`$from\` | \`$to\` | $(expect "$to") | **$result** | ${why:-none} |"
  done < "$STATE/rollback-results.tsv"
} > "$OUT"

caption "Results"
cat "$OUT" | sed -n '/^| From/,$p'
bad=$(awk -F'\t' '{ want = ($2 ~ /pr-482/) ? "FAIL" : "PASS"; if ($3 != want) n++ } END { print n+0 }' "$STATE/rollback-results.tsv")
[ "$bad" = 0 ] && ok "all results as expected (written to docs/rollback-results.md)" || { fail "$bad unexpected result(s)"; exit 1; }
