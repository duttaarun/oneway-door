package onewaydoor.controlcentre.scenario;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.ZoneOffset;
import java.time.ZonedDateTime;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import org.springframework.stereotype.Component;

/**
 * Runs the rollback test for each step of the split and for PR #482, then writes docs/rollback-results.md and the
 * stage-by-stage results the UI shows in act 5. Port of rollback-matrix.sh.
 */
@Component
public class Matrix {

    public static final List<String[]> CASES = List.of(
            new String[] {"main", "split/1-expand"},
            new String[] {"split/1-expand", "split/2-migrate"},
            new String[] {"split/2-migrate", "split/3-contract"},
            new String[] {"split/3-contract", "split/4-drop"},
            new String[] {"main", "pr-482-minor-units"});

    private final RollbackTest test;
    private final Ops ops;

    public Matrix(RollbackTest test, Ops ops) {
        this.test = test;
        this.ops = ops;
    }

    public static String expected(String to) {
        return to.contains("pr-482") ? "FAIL" : "PASS";
    }

    /** Returns true when every case came out as expected (four PASS, one FAIL). */
    public boolean run() throws IOException {
        List<Map<String, Object>> results = new ArrayList<>();
        for (String[] c : CASES) {
            results.add(test.run(c[0], c[1]));
        }
        String generated = ZonedDateTime.now(ZoneOffset.UTC).format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm 'UTC'"));
        Files.writeString(ops.workspace.root().resolve("docs/rollback-results.md"), markdown(results, generated));
        Path recordings = ops.workspace.root().resolve("demo/control-centre/recordings");
        Files.createDirectories(recordings);
        Map<String, Object> doc = new LinkedHashMap<>();
        doc.put("generated", generated);
        doc.put("results", results);
        ops.events.json().writerWithDefaultPrettyPrinter()
                .writeValue(recordings.resolve("matrix.json").toFile(), doc);
        long bad = results.stream().filter(r -> !expected((String) r.get("to")).equals(r.get("result"))).count();
        ops.events.caption("Results");
        for (Map<String, Object> r : results) {
            ops.events.log("PASS".equals(r.get("result")) ? "ok" : "fail",
                    String.format("  %-18s → %-20s %s", r.get("from"), r.get("to"), r.get("result")));
        }
        if (bad == 0) {
            ops.events.ok("all results as expected (written to docs/rollback-results.md)");
        } else {
            ops.events.fail(bad + " unexpected result(s)");
        }
        ops.events.publish("matrix", doc);
        return bad == 0;
    }

    public static String markdown(List<Map<String, Object>> results, String generated) {
        StringBuilder md = new StringBuilder();
        md.append("# Rollback test results\n\n");
        md.append("Generated by the demo Control Centre (`demo/control-centre`, Run all in act 5) on ").append(generated).append(".\n");
        md.append("Each row: clean start at *from*, deploy ledger-service then settlement-service at *to*, roll ledger-service\n");
        md.append("back, then settlement-service, with 20 settlements after every step. PASS means every stage had both services\n");
        md.append("healthy, every settlement booked once, no £0.00 rows, an empty dead-letter topic and a correct reconciliation total.\n\n");
        md.append("| From | To | Expected | Result | First problem |\n");
        md.append("|---|---|---|---|---|\n");
        for (Map<String, Object> r : results) {
            Object why = r.get("firstProblem");
            md.append("| `").append(r.get("from")).append("` | `").append(r.get("to")).append("` | ")
                    .append(expected((String) r.get("to"))).append(" | **").append(r.get("result")).append("** | ")
                    .append(why == null ? "none" : why).append(" |\n");
        }
        return md.toString();
    }
}
